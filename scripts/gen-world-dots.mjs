// Generates an accurate dot-matrix world map (Bloomberg/JARVIS style).
// Samples a hex-offset grid in pixel space, tests point-in-land against
// real 50m coastline geometry, emits normalized [x,y] coords (0..1) that
// match the component's equirectangular projection exactly.
//
// Run: node scripts/gen-world-dots.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const W = 900, H = 440;
const STEP = 5;          // px grid spacing
const HEX = true;        // offset alternate rows for premium hex look

const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-50m.json", "utf8"));
const land = feature(topo, topo.objects.land);

// equirectangular inverse — must match component's proj()
const toLonLat = (x, y) => [(x / W) * 360 - 180, 90 - (y / H) * 180];

const dots = [];
let row = 0;
for (let y = STEP / 2; y < H; y += STEP * 0.88, row++) {
  const xOff = HEX && row % 2 ? STEP / 2 : 0;
  for (let x = STEP / 2 + xOff; x < W; x += STEP) {
    const [lon, lat] = toLonLat(x, y);
    if (lat > 84 || lat < -60) continue; // trim antarctic sliver + pole noise
    if (geoContains(land, [lon, lat])) {
      // normalized, 4-dp to keep file small
      dots.push([+(x / W).toFixed(4), +(y / H).toFixed(4)]);
    }
  }
}

const body =
  `// AUTO-GENERATED by scripts/gen-world-dots.mjs — do not edit by hand.\n` +
  `// Accurate land dot-matrix (50m coastlines), normalized to [0,1] in an\n` +
  `// equirectangular projection. ${dots.length} dots.\n` +
  `export const WORLD_DOTS: [number, number][] = ${JSON.stringify(dots)};\n`;

writeFileSync("src/app/guru/_components/world-dots.ts", body);
console.log(`wrote ${dots.length} dots → src/app/guru/_components/world-dots.ts`);
